// ─────────────────────────────────────────────────────────────
// 4. 60秒脚本
// ─────────────────────────────────────────────────────────────
function buildScript60s(ctx) {
  const t  = ctx.topic;
  const tn = ctx.tone;

  return {
    totalSeconds: 60,
    segments: [
      {
        label:   '开头钩子',
        seconds: '0–5s',
        script:  `（直视镜头，语速稍快）${tn.opener}，关于${t}，有个关键点99%的人都忽略了。`,
        note:    '不要废话，第一句就是信息。',
      },
      {
        label:   '建立痛点共鸣',
        seconds: '5–15s',
        script:  `很多人在${t}上卡了很久——感觉自己一直在做，但就是看不到结果。其实问题出在方向，不是努力程度。`,
        note:    '说出观众心声，让他们觉得"说的就是我"。',
      },
      {
        label:   '核心内容 · 第一点',
        seconds: '15–30s',
        script:  `第一点：先搞清楚你真正要解决的问题是什么。大多数人跳过这步直接行动，结果忙了一圈回到原点。（举例：就像导航没设终点，开得再快也没用。）`,
        note:    '一个类比胜过三段说教。',
      },
      {
        label:   '核心内容 · 第二点',
        seconds: '30–45s',
        script:  `第二点：把大目标拆成最小可执行单元。不是"我要做好${t}"，而是"我今天做这一件具体的事"。小赢积累才能建立正向循环。`,
        note:    '给出可操作步骤，避免停留在概念层面。',
      },
      {
        label:   '结尾行动号召',
        seconds: '45–60s',
        script:  `这两点说起来简单，但真正执行的人不到10%。${tn.cta}（停顿）如果你觉得有用，点个收藏，我们下期继续聊。`,
        note:    '结尾要有"下一步"指引，降低用户离开的动机。',
      },
    ],
  };
}

// ─────────────────────────────────────────────────────────────
// 5. 图文文案
// ─────────────────────────────────────────────────────────────
function buildCopywriting(ctx) {
  const t  = ctx.topic;
  const tn = ctx.tone;
  const emoji = ctx.style === '专业' ? '' : '🌿';

  const platformSuffix = {
    小红书: '\n\n#个人成长 #干货分享 #自我提升',
    抖音:   '',
    视频号: '',
    公众号: '\n\n---\n👇 点击「在看」，让更多人看到这篇文章',
  }[ctx.primaryPlatform] || '';

  return {
    title: `关于${t}，有件事我想认真跟你说 ${emoji}`,
    body: `${tn.opener}。

很多人在${t}上花了大量时间，却始终感觉差一口气——不是能力不够，而是有几个关键认知从来没人讲清楚。

**先问自己一个问题**
你现在对${t}的期待，是真实的需求，还是焦虑催生的冲动？分清楚这两件事，后面做什么都会顺很多。

**第一步：缩小战场**
不要同时推进所有方向。找到一个最小切口，把它做深、做透，比铺开十件事都做到60分有效得多。

**第二步：建立反馈机制**
每做一个阶段，问自己：这步的结果是我想要的吗？很多人一直努力却一直迷茫，就是缺这一步自我校准。

**最后想说的**
关于${t}，没有一条路适合所有人。但有一件事是共通的：先想清楚，再动手，比埋头猛冲，结果要好得多。

${tn.cta}${platformSuffix}`,
  };
}

// ─────────────────────────────────────────────────────────────
// 6. 去AI味建议
// ─────────────────────────────────────────────────────────────
function buildDeAiSuggestions(ctx) {
  return [
    {
      problem: '段落开头用"首先、其次、最后"等排比结构',
      fix:     '换成口语转折，如"说到这里要停一下"、"等等，这里有个坑"，或直接用数字序号但加语气词',
      example: '❌ 首先你需要明确目标。✅ 先停下来想一件事——你现在的目标，是你真正想要的吗？',
    },
    {
      problem: '用"总的来说""综上所述"收尾',
      fix:     '用一句有画面感的话代替总结，或直接抛出下一个问题引发思考',
      example: '❌ 综上所述，做好这三点非常重要。✅ 说到底，我遇到的人里，真正做到这件事的，没几个后悔的。',
    },
    {
      problem: '句子太整齐、太对称，读起来像说明书',
      fix:     '故意打破节奏：短句之后接一个长句；或加一句"题外话"式的插叙',
      example: '❌ 方法一、方法二、方法三，每条都有固定价值。✅ 前两个你可能听过，但第三个……说出来可能有人不同意我。',
    },
    {
      problem: '缺少第一人称的真实经历',
      fix:     '加入一个具体的个人细节，哪怕是虚构的场景感。"我有个朋友""上周有人问我"都比泛泛而谈有力',
      example: '❌ 很多人都会遇到这种情况。✅ 上个月我自己就卡在这里，反复想了好几天才想通。',
    },
    {
      problem: '正确但无聊——说的都对，但没有记忆点',
      fix:     `加一个反常识结论或出人意料的类比，让读者有"等等，原来是这样"的停顿感`,
      example: '❌ 坚持很重要，量变引起质变。✅ 我后来发现，坚持本身没用——有用的是让坚持变得不需要意志力。',
    },
  ];
}

// ─────────────────────────────────────────────────────────────
// 7. 风险提示
// ─────────────────────────────────────────────────────────────
function buildRiskWarnings(ctx) {
  const platformRisks = {
    小红书: '避免出现"最""第一""最好"等绝对化表述，小红书会限流含违规词的笔记。',
    抖音:   '前3秒若出现文字遮挡面部或大段静态画面，系统会降低推流权重。',
    视频号:  '视频号对外链跳转敏感，文案中不要出现引导至其他平台的文字。',
    公众号:  '公众号文章若含诱导分享/关注的明确话术，可能触发平台审核。',
  };

  const styleRisks = {
    犀利:  '犀利风格容易被截图断章取义，注意不要出现绝对化批判某类人群的表述。',
    专业:  '专业风格引用数据需标注来源，否则被质疑时容易失去公信力。',
    温暖:  '温暖风格要避免陷入"说教感"，保持倾听者姿态而非给答案的导师姿态。',
    口语化: '口语化表述要注意平台调性，过于随意的语气在公众号可能显得不专业。',
  };

  const warnings = [];

  ctx.platforms.forEach(p => {
    if (platformRisks[p]) warnings.push({ type: '平台规则', platform: p, content: platformRisks[p] });
  });

  if (styleRisks[ctx.style]) {
    warnings.push({ type: '风格风险', platform: null, content: styleRisks[ctx.style] });
  }

  warnings.push({
    type: '内容同质化',
    platform: null,
    content: `关于"${ctx.topic}"的内容已有大量创作者在做。建议加入你的亲身经历或反常识角度，否则难以从信息流中突围。`,
  });

  return warnings;
}

