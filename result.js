/**
 * generateResult(topic, platforms, style)
 * 根据选题、平台、风格生成内容结果对象（当前为模拟数据）。
 * 后续替换 MOCK_DATA 内部逻辑，接入真实 API 即可。
 *
 * @param {string}   topic     - 用户输入的选题 / 文案
 * @param {string[]} platforms - 选中的平台数组，如 ['小红书', '抖音']
 * @param {string}   style     - 内容风格，如 '温暖' | '犀利' | '专业' | '口语化'
 * @returns {ContentResult}
 */
function generateResult(topic, platforms, style) {
  const ctx = buildContext(topic, platforms, style);
  return {
    meta: ctx,
    painPoint:       buildPainPoint(ctx),
    titles:          buildTitles(ctx),
    hooks:           buildHooks(ctx),
    script60s:       buildScript60s(ctx),
    copywriting:     buildCopywriting(ctx),
    deAiSuggestions: buildDeAiSuggestions(ctx),
    riskWarnings:    buildRiskWarnings(ctx),
    coverTexts:      buildCoverTexts(ctx),
  };
}

// ─────────────────────────────────────────────────────────────
// Context builder — extracts keywords and tone settings
// ─────────────────────────────────────────────────────────────
function buildContext(topic, platforms, style) {
  const primaryPlatform = platforms[0] || '小红书';
  const isShortVideo = ['抖音', '视频号'].some(p => platforms.includes(p));
  const isLongForm   = platforms.includes('公众号');

  // Style tone map
  const toneMap = {
    温暖:  { opener: '想跟你聊一件很多人都忽视的事',  cta: '希望对你有一点点帮助 🌿',      pronoun: '我们' },
    犀利:  { opener: '说一个可能让你不舒服的真相',    cta: '现在就开始改变，别等了。',     pronoun: '你' },
    专业:  { opener: '数据告诉我们一个关键结论',      cta: '欢迎收藏备用，随时查阅。',     pronoun: '大家' },
    口语化: { opener: '哎我最近发现一件事，超有感触', cta: '你们有没有同感？评论区见 👇', pronoun: '咱们' },
  };

  return {
    topic,
    platforms,
    primaryPlatform,
    isShortVideo,
    isLongForm,
    style,
    tone: toneMap[style] || toneMap['温暖'],
  };
}

// ─────────────────────────────────────────────────────────────
// 1. 痛点判断
// ─────────────────────────────────────────────────────────────
function buildPainPoint(ctx) {
  return {
    // 核心痛点：用户真正在意什么
    core: `读者表面在意"${ctx.topic}"，实际上担心的是：自己在同龄人中是否落后、是否在浪费时间。`,

    // 情绪触发词：能引发共鸣的关键词
    emotionTriggers: ['已经来不及了？', '别人都在做', '我是不是太晚了', '偷偷努力'],

    // 目标读者画像
    audienceProfile: `25-35岁、有上进心但行动力不稳定、容易焦虑的${ctx.primaryPlatform}用户。他们刷内容的深层动机：寻找"我也可以"的确认感。`,

    // 平台特性提示
    platformNote: `${ctx.primaryPlatform}用户决定继续看的平均时间窗口：${ctx.isShortVideo ? '前 3 秒' : '前 2 行文字'}。你的内容必须在这个窗口内命中痛点。`,
  };
}

// ─────────────────────────────────────────────────────────────
// 2. 10个标题
// ─────────────────────────────────────────────────────────────
function buildTitles(ctx) {
  const t = ctx.topic;
  const stylePrefix = {
    温暖:  ['写给', '给还在', '那些'],
    犀利:  ['没人告诉你', '你以为的', '停止'],
    专业:  ['拆解：', '数据实证：', '完整方法论：'],
    口语化: ['真的，', '说真的，', '我是怎么'],
  }[ctx.style] || [''];

  return [
    // 数字型
    `${t}的 7 个关键动作，第 3 个大多数人都做错了`,
    `做到这 3 点，关于${t}你就赢了 90%`,
    // 对比冲突型
    `同样是${t}，为什么有人越做越好，有人原地踏步`,
    `不是你不努力，是${t}的方式根本就错了`,
    // 悬念钩子型
    `我研究了 100 个案例，发现${t}最容易踩的坑`,
    `关于${t}，有件事我之前一直不敢说`,
    // 利益承诺型
    `${t}的底层逻辑，看完这篇你就全懂了`,
    `${stylePrefix[0]}还没搞清楚${t}的人：这篇请收好`,
    // 身份代入型
    `普通人如何靠${t}完成逆袭？我亲历的真实过程`,
    // 反常识型
    `${t}最大的误区：越努力越错，直到我想通这件事`,
  ];
}

